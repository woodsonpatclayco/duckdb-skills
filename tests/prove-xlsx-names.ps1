<#
tests\prove-xlsx-names.ps1 -- read_xlsx_name edge cases, on a generated fixture.

The real workbooks prove-xlsx-tables.ps1 reads hold no one-cell names and no name defined at
both workbook and sheet scope, so these two cases are proven here on
extension\xlsx_meta\test\data\tables.xlsx (generated by extension\xlsx_meta\test\make_fixtures.py;
the C++ extension's tests read the same file):

  one-cell names   read_xlsx rejects range='A1', so read_xlsx_name used to fail on every
                   one-cell name. It now widens the range to A1:A1; xlsx_name_range still
                   returns 'A1' because xlsx__one_cell (formula checks) depends on it.
  both scopes      Dup at workbook scope and Rates!dup at sheet scope is not ambiguous: the bare
                   name means the workbook one, as in Excel, and the sheet one is reached by
                   prefixing its sheet -- Rates!dup, 'Rates'!dup, any case.

Then the refusals that must still fire, so the change didn't make anything resolve that
shouldn't: a name on two sheets with no workbook definition, a #REF! name, a formula-defined
name, an unknown name.
#>
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$wb   = Join-Path $repo 'extension\xlsx_meta\test\data\tables.xlsx'
$meta = Join-Path $repo 'tools\xlsx_meta.py'
$work = Join-Path ([IO.Path]::GetTempPath()) 'prove-xlsx-names'
New-Item -ItemType Directory -Force $work | Out-Null

$macros = Join-Path $work 'macros.sql'
& py -3.12 $meta macros $wb -o $macros | Out-Null
if ($LASTEXITCODE -ne 0) { throw "xlsx_meta.py macros failed" }
$macrosFwd = $macros.Replace('\', '/')   # duckdb's .read treats \ as an escape

function Sq($s) { "'" + $s.Replace("'", "''") + "'" }
$fail = 0

# Listing: ExternalData_1 (two sheets, no workbook definition) is ambiguous; Dup is not.
$names = & py -3.12 $meta names $wb --format csv | ConvertFrom-Csv
$ambiguous = @($names | Where-Object { $_.status -eq 'ambiguous' } | ForEach-Object { $_.address })
$ok = if (($ambiguous -join ',') -eq 'ExternalData_1') { 'PASS' } else { $fail++; 'FAIL' }
Write-Output "$ok  names lists exactly one ambiguous name, ExternalData_1 (got: $($ambiguous -join ', '))"
Write-Output ''

# Reads: rows returned and the first cell's value, through the generated read_xlsx_name.
$reads = @(
    @{ what = 'one-cell name Title_Cell (A1)';              key = 'Title_Cell';        rows = 1; first = 'Rates sheet title' },
    @{ what = 'bare Dup -> the workbook-scoped one (A3)';   key = 'Dup';               rows = 1; first = 'A100' },
    @{ what = 'Rates!dup -> the sheet-scoped one (B3)';     key = 'Rates!dup';         rows = 1; first = '12.5' },
    @{ what = "'Rates'!dup, quoted though it needn't be";   key = "'Rates'!dup";       rows = 1; first = '12.5' },
    @{ what = 'RATES!DUP, any case';                        key = 'RATES!DUP';         rows = 1; first = '12.5' },
    @{ what = 'multi-row Rate_Block (A2:C5, header row)';   key = 'Rate_Block';        rows = 3; first = 'A100' },
    @{ what = "'Bob''s Data'!Items, quoted sheet";          key = "'Bob''s Data'!Items"; rows = 2; first = 'washer' }
)
Write-Output 'Reads: rows and first value returned by read_xlsx_name'
foreach ($r in $reads) {
    $f = Join-Path $work 'read.sql'
    @(".read $macrosFwd", ".mode csv",
      "SELECT count(*) OVER () AS n, * FROM read_xlsx_name($(Sq $wb), $(Sq $r.key)) LIMIT 1;") |
        Set-Content -Encoding ascii $f
    $out = (cmd /c "duckdb -f `"$f`" 2>&1" | Out-String)
    $code = $LASTEXITCODE
    $got = if ($code -eq 0) { $out | ConvertFrom-Csv } else { $null }
    $n = if ($got) { [int]$got.n } else { 0 }
    $v = if ($got) { @($got.PSObject.Properties)[1].Value } else { ($out -split "`n" | Where-Object { $_ -match 'Error:' } | Select-Object -First 1) }
    $ok = if ($code -eq 0 -and $n -eq $r.rows -and $v -eq $r.first) { 'PASS' } else { $fail++; 'FAIL' }
    Write-Output ("  {0}  {1}: {2} row(s), first value '{3}'" -f $ok, $r.what, $n, "$v".Trim())
}
Write-Output ''

# xlsx_name_range itself keeps the one-cell form: the formula checks' xlsx__one_cell needs it.
$f = Join-Path $work 'range.sql'
@(".read $macrosFwd", ".mode csv",
  "SELECT xlsx_name_range($(Sq $wb), 'Title_Cell') AS r, xlsx__one_cell('Title_Cell', xlsx_name_range($(Sq $wb), 'Title_Cell')) AS c;") |
    Set-Content -Encoding ascii $f
$got = & duckdb -f $f | ConvertFrom-Csv
$ok = if ($LASTEXITCODE -eq 0 -and $got.r -eq 'A1' -and $got.c -eq 'A1') { 'PASS' } else { $fail++; 'FAIL' }
Write-Output "$ok  xlsx_name_range still returns '$($got.r)' for a one-cell name, and xlsx__one_cell accepts it"
Write-Output ''

$refusals = @(
    @{ what = 'bare ExternalData_1 (two sheets, no workbook one)'; key = 'ExternalData_1';   want = 'is ambiguous' },
    @{ what = 'Excluded_Vendors (refers to #REF!)';                key = 'Excluded_Vendors'; want = 'is broken' },
    @{ what = 'Dyn_Range (OFFSET formula)';                        key = 'Dyn_Range';        want = 'is not a plain cell range' },
    @{ what = 'a name that does not exist';                        key = 'Nope';             want = "no defined name 'Nope'" }
)
Write-Output 'Refusals: each of these must stop with an error, not return rows'
foreach ($r in $refusals) {
    $f = Join-Path $work 'refusal.sql'
    @(".read $macrosFwd", "FROM read_xlsx_name($(Sq $wb), $(Sq $r.key));") | Set-Content -Encoding ascii $f
    # cmd merges stderr as plain text; PowerShell 5.1 would wrap each stderr line as an error record.
    $out = (cmd /c "duckdb -f `"$f`" 2>&1" | Out-String)
    $code = $LASTEXITCODE
    $msg = ($out -split "`n" | Where-Object { $_ -match 'Error:' } | Select-Object -First 1)
    $ok = if ($code -ne 0 -and $out -match [regex]::Escape($r.want)) { 'PASS' } else { $fail++; 'FAIL' }
    Write-Output ("  {0}  {1}" -f $ok, $r.what)
    Write-Output ("        {0}" -f ($msg -replace '^\s+', '').Trim())
}
Write-Output ''

if ($fail) { Write-Output "RESULT: FAIL ($fail check(s) failed)"; exit 1 }
Write-Output "RESULT: PASS ($($reads.Count) reads, $($refusals.Count) refusals, listing and one-cell range)"
